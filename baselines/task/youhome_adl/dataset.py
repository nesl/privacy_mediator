"""YouHome ADL dataset for image/audio/fusion baselines.

The manifest is generated by make_manifest.py from:
    data/youhome/data/<participant>/<activity>/<session>/...
    data/youhome/label/<participant>/<activity>/<session>/...

Activity labels come from folder names. Label txt files are optional YOLO-style
person/user bounding boxes used for crop-based privacy variants.
"""
from __future__ import annotations

from pathlib import Path
import random
from typing import Literal

import torch
from torch.utils.data import Dataset
from torchvision import transforms
from PIL import Image, ImageFilter

from baselines.task.common.audio import load_audio
from baselines.task.common.manifest import build_label_map, filter_split, load_manifest, resolve_path
from baselines.task.common.video import sorted_images
from baselines.task.youhome_adl.youhome_layout import label_path_for_image, parse_yolo_label_file

ImageMode = Literal["full", "crop", "blur", "lowres", "none"]
TrainFrameSampling = Literal["random", "uniform"]


class YouHomeAVDataset(Dataset):
    def __init__(
        self,
        manifest_path: str | Path,
        data_root: str | Path | None = None,
        split: str | None = None,
        label_map: dict[str, int] | None = None,
        image_size: int = 224,
        num_frames: int = 4,
        image_mode: ImageMode = "full",
        sample_rate: int = 16000,
        audio_duration: float = 10.0,
        random_audio_crop: bool = False,
        random_audio_crop_eval: bool = False,
        training: bool = False,
        train_frame_sampling: TrainFrameSampling = "random",
        strict_missing: bool = False,
    ) -> None:
        self.df = filter_split(load_manifest(manifest_path), split)
        if "label" not in self.df.columns:
            raise ValueError("Manifest must contain label")
        self.data_root = Path(data_root) if data_root is not None else None
        self.label_map = label_map or build_label_map(self.df["label"].tolist())
        self.sample_rate = sample_rate
        self.audio_duration = audio_duration
        self.random_audio_crop = bool(random_audio_crop and (training or random_audio_crop_eval))
        self.training = training
        self.strict_missing = strict_missing
        self.num_frames = max(1, int(num_frames))
        self.image_mode = image_mode
        self.train_frame_sampling = train_frame_sampling

        if training:
            self.image_tf = transforms.Compose([
                transforms.RandomResizedCrop(image_size, scale=(0.70, 1.0)),
                transforms.RandomHorizontalFlip(),
                transforms.RandomRotation(6),
                transforms.ColorJitter(brightness=0.15, contrast=0.15, saturation=0.10, hue=0.02),
                transforms.ToTensor(),
                transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
            ])
        else:
            self.image_tf = transforms.Compose([
                transforms.Resize(image_size + 32),
                transforms.CenterCrop(image_size),
                transforms.ToTensor(),
                transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
            ])
        self.blank_image = torch.zeros(3, image_size, image_size)
        self.blank_audio = torch.zeros(int(sample_rate * audio_duration))

    def __len__(self) -> int:
        return len(self.df)

    @staticmethod
    def _clean_path_value(value) -> str | None:
        """Normalize pandas/CSV path values and treat blanks/NaN as missing."""
        if value is None:
            return None
        text = str(value).strip()
        if not text or text.lower() in {"nan", "none", "null"}:
            return None
        return text

    def _candidate_paths(self, value, *, append_audio_name: bool = False) -> list[Path]:
        """Return plausible interpretations of a manifest path.

        The YouHome tree is commonly rooted as:
            data/youhome/data/<participant>/<activity>/<session>/audio.wav

        Depending on how a manifest was generated, paths may be stored as:
        absolute paths, paths relative to the current working directory, paths
        relative to --data-root, or paths relative to --data-root/data.  Try all
        of those before declaring a sample missing.
        """
        text = self._clean_path_value(value)
        if text is None:
            return []
        raw = Path(text).expanduser()
        bases: list[Path] = []
        if raw.is_absolute():
            bases.append(raw)
        else:
            bases.append(raw)
            if self.data_root is not None:
                bases.append(self.data_root / raw)
                bases.append(self.data_root / "data" / raw)
                # If the manifest already contains a prefix such as
                # data/youhome/data/..., avoid double-prefixing by also trying
                # the suffix that starts at the YouHome data/ directory.
                parts = raw.parts
                if "data" in parts:
                    for i, part in enumerate(parts):
                        if part == "data" and i + 1 < len(parts):
                            bases.append(self.data_root / Path(*parts[i:]))
                            bases.append(self.data_root / "data" / Path(*parts[i + 1:]))
                            break
        out: list[Path] = []
        seen: set[str] = set()
        for base in bases:
            candidates = [base]
            if append_audio_name:
                if base.suffix.lower() == ".wav":
                    candidates.append(base)
                else:
                    candidates.append(base / "audio.wav")
                    candidates.append(base.parent / "audio.wav")
            for cand in candidates:
                key = str(cand)
                if key not in seen:
                    seen.add(key)
                    out.append(cand)
        return out

    def _first_existing_path(self, candidates: list[Path]) -> Path | None:
        for p in candidates:
            if p.exists():
                return p
        return None

    def _resolve_audio_path(self, row) -> Path | None:
        """Resolve audio.wav robustly, including deriving it from frame/image dirs."""
        candidates: list[Path] = []
        candidates.extend(self._candidate_paths(row.get("audio_path", None), append_audio_name=True))

        # Some manifests omit audio_path or store it with a different name.
        for col in ("audio", "sound_path", "wav_path", "audio_file"):
            candidates.extend(self._candidate_paths(row.get(col, None), append_audio_name=True))

        # Fallback: derive session audio from image/frame/label locations.
        for col in ("frame_dir", "image_path", "label_dir"):
            for p in self._candidate_paths(row.get(col, None), append_audio_name=False):
                if p.suffix:
                    candidates.extend([p.parent / "audio.wav", p.parent.parent / "audio.wav"])
                else:
                    candidates.extend([p / "audio.wav", p.parent / "audio.wav"])

        # De-duplicate while preserving order.
        deduped: list[Path] = []
        seen: set[str] = set()
        for p in candidates:
            key = str(p)
            if key not in seen:
                seen.add(key)
                deduped.append(p)
        return self._first_existing_path(deduped)

    def _choose_images(self, row) -> list[Path]:
        frame_dir = resolve_path(row.get("frame_dir", None), self.data_root)
        if frame_dir is None or not frame_dir.exists():
            image_path = resolve_path(row.get("image_path", None), self.data_root)
            return [image_path] if image_path is not None and image_path.exists() else []
        imgs = sorted_images(frame_dir)
        if not imgs:
            return []
        if self.training:
            if len(imgs) >= self.num_frames:
                if self.train_frame_sampling == "uniform":
                    # Deterministic coverage with mild random jitter from the starting offset.
                    idxs = torch.linspace(0, len(imgs) - 1, steps=self.num_frames).round().long().tolist()
                    return [imgs[i] for i in idxs]
                return sorted(random.sample(imgs, self.num_frames))
            return imgs + [imgs[-1]] * (self.num_frames - len(imgs))
        if len(imgs) == 1:
            return [imgs[0]] * self.num_frames
        # Evenly spaced deterministic frames for validation/test.
        idxs = torch.linspace(0, len(imgs) - 1, steps=self.num_frames).round().long().tolist()
        return [imgs[i] for i in idxs]

    def _crop_using_label(self, img: Image.Image, img_path: Path, row) -> Image.Image:
        label_dir = resolve_path(row.get("label_dir", None), self.data_root)
        if label_dir is None or not label_dir.exists():
            return img
        label_file = label_path_for_image(img_path, label_dir)
        boxes = parse_yolo_label_file(label_file)
        if not boxes:
            return img
        # Use largest box if multiple people/users are annotated.
        box = max(boxes, key=lambda b: b["width"] * b["height"])
        W, H = img.size
        xc, yc, bw, bh = box["x_center"], box["y_center"], box["width"], box["height"]
        pad = 0.10
        x1 = max(0, int((xc - bw / 2 - pad * bw) * W))
        y1 = max(0, int((yc - bh / 2 - pad * bh) * H))
        x2 = min(W, int((xc + bw / 2 + pad * bw) * W))
        y2 = min(H, int((yc + bh / 2 + pad * bh) * H))
        if x2 <= x1 or y2 <= y1:
            return img
        return img.crop((x1, y1, x2, y2))

    def _apply_image_mode(self, img: Image.Image, img_path: Path, row) -> Image.Image:
        if self.image_mode == "full":
            return img
        if self.image_mode == "crop":
            return self._crop_using_label(img, img_path, row)
        if self.image_mode == "blur":
            return img.filter(ImageFilter.GaussianBlur(radius=8))
        if self.image_mode == "lowres":
            small = img.resize((max(1, img.width // 8), max(1, img.height // 8)), Image.BILINEAR)
            return small.resize(img.size, Image.NEAREST)
        if self.image_mode == "none":
            return Image.new("RGB", img.size, color=(0, 0, 0))
        raise ValueError(f"Unsupported image_mode={self.image_mode}")

    def _load_images(self, row) -> tuple[torch.Tensor, bool]:
        paths = self._choose_images(row)
        if not paths:
            if self.strict_missing:
                raise FileNotFoundError(f"No images found for sample_id={row.get('sample_id', '<unknown>')}")
            return torch.stack([self.blank_image.clone() for _ in range(self.num_frames)], dim=0), True

        tensors = []
        had_error = False
        for p in paths[: self.num_frames]:
            try:
                img = Image.open(p).convert("RGB")
                img = self._apply_image_mode(img, p, row)
                tensors.append(self.image_tf(img))
            except Exception as exc:
                if self.strict_missing:
                    raise RuntimeError(f"Failed to load image {p}") from exc
                had_error = True
                tensors.append(self.blank_image.clone())
        while len(tensors) < self.num_frames:
            tensors.append(tensors[-1].clone() if tensors else self.blank_image.clone())
        return torch.stack(tensors, dim=0), had_error

    def _finalize_audio(self, waveform: torch.Tensor) -> torch.Tensor:
        """Return a 1-D float waveform with exactly sample_rate * audio_duration samples.

        This makes the dataset robust to different implementations of
        baselines.task.common.audio.load_audio. Some versions already crop/pad;
        others simply decode. Keeping the final length check here prevents shape
        surprises in the DataLoader.
        """
        wav = torch.as_tensor(waveform).detach().float()
        if wav.ndim == 0:
            return self.blank_audio.clone()
        if wav.ndim > 1:
            # torchaudio returns [channels, time]. If a loader returns [time, channels],
            # averaging the smaller dimension is still a safe mono conversion for common cases.
            if wav.shape[0] <= wav.shape[-1]:
                wav = wav.mean(dim=0)
            else:
                wav = wav.mean(dim=-1)
        wav = wav.flatten()

        target_len = int(self.sample_rate * self.audio_duration)
        if target_len <= 0:
            return wav
        if wav.numel() == target_len:
            return wav
        if wav.numel() > target_len:
            if self.random_audio_crop:
                max_start = wav.numel() - target_len
                start = int(torch.randint(0, max_start + 1, (1,)).item())
            else:
                start = 0
            return wav[start:start + target_len].contiguous()
        pad = torch.zeros(target_len - wav.numel(), dtype=wav.dtype)
        return torch.cat([wav, pad], dim=0)

    def _load_audio_common_no_random_crop(self, p: Path) -> torch.Tensor:
        """Call the project load_audio function without assuming random_crop support."""
        try:
            wav = load_audio(str(p), sample_rate=self.sample_rate, duration=self.audio_duration)
        except TypeError:
            # Older local helper variants may not support duration either.
            try:
                wav = load_audio(str(p), sample_rate=self.sample_rate)
            except TypeError:
                wav = load_audio(str(p))
        return self._finalize_audio(wav)

    def _load_audio_with_torchaudio(self, p: Path) -> torch.Tensor:
        """Fallback decoder used when we need random cropping but load_audio lacks it."""
        import torchaudio

        wav, sr = torchaudio.load(str(p))
        wav = wav.float()
        if wav.ndim == 2:
            wav = wav.mean(dim=0)
        if int(sr) != int(self.sample_rate):
            wav = torchaudio.functional.resample(wav, int(sr), int(self.sample_rate))
        return self._finalize_audio(wav)

    def _load_audio(self, row) -> tuple[torch.Tensor, bool]:
        p = self._resolve_audio_path(row)
        if p is None or not p.exists():
            if self.strict_missing:
                tried = [str(x) for x in self._candidate_paths(row.get("audio_path", None), append_audio_name=True)]
                raise FileNotFoundError(
                    f"No audio found for sample_id={row.get('sample_id', '<unknown>')}. "
                    f"audio_path={row.get('audio_path', None)!r}; tried={tried[:8]}"
                )
            return self.blank_audio.clone(), True

        try:
            try:
                wav = load_audio(
                    str(p),
                    sample_rate=self.sample_rate,
                    duration=self.audio_duration,
                    random_crop=self.random_audio_crop,
                )
                return self._finalize_audio(wav), False
            except TypeError as exc:
                # Your local load_audio() does not accept random_crop. Previously this
                # was caught by the broad exception handler below, causing every valid
                # audio file to become a blank tensor and audio_missing=True.
                if "random_crop" not in str(exc):
                    raise
                if self.random_audio_crop:
                    return self._load_audio_with_torchaudio(p), False
                return self._load_audio_common_no_random_crop(p), False
        except Exception as exc:
            if self.strict_missing:
                raise RuntimeError(f"Failed to load audio {p}") from exc
            return self.blank_audio.clone(), True

    def __getitem__(self, index: int):
        row = self.df.iloc[index]
        label_name = str(row["label"])
        if label_name not in self.label_map:
            raise KeyError(f"Label {label_name!r} missing from label_map")
        label = self.label_map[label_name]
        image, image_missing = self._load_images(row)
        audio, audio_missing = self._load_audio(row)
        return {
            "image": image,
            "audio": audio,
            "label": torch.tensor(label, dtype=torch.long),
            "sample_id": str(row.get("sample_id", index)),
            "label_name": label_name,
            "image_missing": torch.tensor(bool(image_missing)),
            "audio_missing": torch.tensor(bool(audio_missing)),
        }
